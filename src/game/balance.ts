/**
 * 계단 타이머 (한 칸에 머무를 수 있는 시간).
 *
 * 한 칸을 밟을 때마다 다시 찬다. 0 이 되면 판이 끝난다 — 계단을 오르는 구간에
 * "생각할 시간"이 아니라 "리듬"을 요구하는 장치다.
 *
 * **높은 층일수록 짧아지고 하한은 2초다.** 하한이 없으면 어느 층부터는 인간이
 * 반응할 수 없는 시간이 되어 실력과 무관하게 끝난다.
 * **보스전에는 적용하지 않는다** — 보스전은 계단이 잠기고 문제를 푸는 구간이므로
 * 계단 시간을 재는 것이 의미가 없고, 문제를 읽을 시간을 빼앗으면 안 된다.
 */
/**
 * 계단 게이지 — **원작(무한의 계단)의 방식**.
 *
 * ## 왜 "칸마다 N초" 를 버렸나
 *
 * 이전에는 한 칸을 밟을 때마다 타이머를 3초로 되돌렸다. 그러면 매 칸이 독립된 3초짜리
 * 마감이 되어 **리듬이 생기지 않는다** — 빨리 올라도 이득이 없고, 한 칸마다 3초를
 * 쉬어도 아무 일이 없다. "너무 여유롭고 리드미컬하지 않다"는 지적이 정확했다.
 *
 * 원작은 **하나의 게이지가 계속 줄고, 한 칸 오를 때마다 조금씩 채워진다.** 그래서
 *  · 빠르게 오르면 게이지가 쌓여 **여유를 번다**
 *  · 망설이면 벌어 둔 여유가 깎인다
 *  · 게이지가 0 이면 끝난다
 *
 * 압박이 칸 단위가 아니라 **속도 단위**로 바뀐다. 이것이 리듬이다.
 *
 * ## 손익분기 속도
 *
 * 한 칸에 `gainFor(층)` 초가 채워지므로, **그보다 빠르게 밟으면 게이지가 는다.**
 * 0층 0.62초/칸(느긋해도 유지) → 300층 0.42초/칸 → 하한 0.34초/칸.
 * 점프가 0.17초이므로 하한에서도 사람이 낼 수 있는 속도다.
 */
export const STAIR_GAUGE = {
  /**
   * 게이지 상한(초) — 아무리 빨리 올라도 이만큼까지만 벌어 둔다.
   *
   * 가득 찼을 때 **3초를 쉴 수 있다.** 이전 규칙의 하한(2초)보다 여유가 크지만,
   * 그 여유를 **벌어야** 갖는다는 점이 다르다.
   */
  capacity: 3,
  /**
   * 판 시작·보스 처치 직후 채우는 양(초) — **가득 채운다.**
   *
   * 원작도 게이지가 가득 찬 채 시작한다. 첫 칸의 방향을 읽을 시간이 필요하고,
   * 보스를 넘긴 직후에는 한숨 돌릴 자격이 있다. 줄이는 것은 그 뒤 아이의 속도가 한다.
   */
  startFill: 3,
  /** 0층에서 한 칸에 채워지는 양(초) = 그 층의 손익분기 속도 */
  gainAtFloor0: 0.62,
  /** 100층마다 곱하는 비율 — 위로 갈수록 더 빨리 밟아야 유지된다 */
  gainRatioPer100: 0.88,
  /** 채워지는 양의 하한(초). 이보다 빠른 속도를 요구하지 않는다 */
  minGain: 0.34,
} as const;

/**
 * 그 층에서 한 칸을 밟을 때 채워지는 양(초).
 *
 * 이 값이 곧 **손익분기 속도**다 — 이보다 빨리 밟으면 게이지가 쌓이고, 느리면 줄어든다.
 * 0층 0.62 · 100층 0.55 · 200층 0.48 · 300층 0.42 · 400층 0.37 · 470층부터 0.34 고정.
 */
export function gaugeGainFor(floor: number): number {
  const raw =
    STAIR_GAUGE.gainAtFloor0 * Math.pow(STAIR_GAUGE.gainRatioPer100, Math.max(0, floor) / 100);
  return Math.max(STAIR_GAUGE.minGain, raw);
}

